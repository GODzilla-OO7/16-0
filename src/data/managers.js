// Returns an interleaved list that spreads wcWinner coaches evenly for the reel display
export function getInterleavedManagers(mode) {
  const winners = MANAGERS.filter(m => m.wcWinnerFor?.includes(mode))
  const others  = MANAGERS.filter(m => !m.wcWinnerFor?.includes(mode))
  if (winners.length === 0) return MANAGERS

  const result = []
  const step = Math.max(1, Math.floor(others.length / (winners.length + 1)))
  let wi = 0, oi = 0

  while (wi < winners.length || oi < others.length) {
    // add `step` others, then one winner
    for (let s = 0; s < step && oi < others.length; s++) result.push(others[oi++])
    if (wi < winners.length) result.push(winners[wi++])
  }
  // any remaining others
  while (oi < others.length) result.push(others[oi++])
  return result
}
